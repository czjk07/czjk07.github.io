#!/usr/bin/env python3
"""Parse the markdown question bank into questions.js for the web app.

Usage: python3 tools/parse_questions.py <input.md> <output questions.js>
"""
import json
import re
import sys


def parse(path: str) -> list[dict]:
    text = open(path, encoding="utf-8").read()
    # Track current ## section for display purposes.
    section = ""
    questions = []
    # Walk the file keeping the current section header.
    pos = 0
    pattern = re.compile(r"^(## .+|### .+)$", re.M)
    matches = list(pattern.finditer(text))
    for i, m in enumerate(matches):
        header = m.group(1)
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        if header.startswith("## "):
            section = header[3:].strip()
            continue
        block = text[m.end():end]
        number = header[4:].strip()
        qm = re.search(r"\*\*(.+?)\*\*", block, flags=re.S)
        question = re.sub(r"\s+", " ", qm.group(1)).strip() if qm else ""
        options = [t.strip() for _l, t in re.findall(r"^- ([a-e])\.\s*(.+)$", block, flags=re.M)]
        am = re.search(r"\*\*Správná odpověď:\*\*\s*\*\*([a-e])\.", block)
        letter = am.group(1) if am else None
        em = re.search(r"^> \*Vysvětlení:\*\s*(.*)$", block, flags=re.M)
        explanation = re.sub(r"\s+", " ", em.group(1)).strip() if em else ""
        if not question or letter is None or not options:
            raise ValueError(f"Malformed block: {header}")
        answer = ord(letter) - ord("a")
        if answer >= len(options):
            raise ValueError(f"Answer {letter} out of range in: {header}")
        questions.append({
            "number": number,
            "section": section,
            "q": question,
            "options": options,
            "answer": answer,
            "explanation": explanation,
        })
        pos += 1
    return questions


def main() -> None:
    src, dst = sys.argv[1], sys.argv[2]
    questions = parse(src)
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/parse_questions.py - do not edit by hand.\n")
        f.write("window.QUESTIONS = ")
        f.write(json.dumps(questions, ensure_ascii=False, indent=1))
        f.write(";\n")
    print(f"Wrote {len(questions)} questions to {dst}")


if __name__ == "__main__":
    main()
